#!/bin/sh
# Stage the files a PS3 needs to join OpenPak's PSN replacement, and emit the VSH-plugin poke
# header from whatever CA the OpenPak network profile serves. No console is touched here; this
# only produces dist/ for you to copy over (see docs/deploy.md).
#
#   tools/stage.sh [ca.pem]
#
# With no argument the CA is fetched from the ps3 network profile and checked against its sha256
# pin (the same contract as scratch/pier/install-ca.sh). Pass a local PEM to stage that instead
# (its CN still drives the pokes).
#
# Output:
#   dist/dev_flash/data/cert/CA01.cer   the OpenPak CA (PEM; CAnn.cer are PEM on this firmware)
#   dist/dev_flash/data/cert/CA59.cer   same file (the NP login service reads CA01-05; the boot
#                                       store reads CA01..CA59 -- we occupy both ends)
#   plugin/openpak_ca_patch.h           the three vsh pokes, generated from the CA's CN
#   dist/poke-table.txt                 the same pokes in human-readable form (for docs / webMAN)
#   plugin/openpak_names.h              the PSN name rewrite table, from names/psn-names.txt
#                                       (+ the file named by NAMES_EXTRA, same format)
set -e

PROFILE_URL='https://openpak.org/api/v1/network/profile?platform=ps3'
D=$(cd "$(dirname "$0")/.." && pwd)        # repo root
CERT="$D/dist/dev_flash/data/cert"
HDR="$D/plugin/openpak_ca_patch.h"

# 4.93 retail CEX vsh.self addresses (see research/ps3/console-setup.md). Re-derive for any other
# firmware by byte pattern and override via the environment before running stage.
: "${ADDR_SHA1_BRANCH:=0x589198}"      # bf 30,+8 -> nop   (file-content gate)
: "${ADDR_CN_CMPLEN:=0x22ca08}"        # cmpwi cr7,r0,17   -> cmpwi cr7,r0,<len>
: "${ADDR_CN_MEMLEN:=0x22ca1c}"        # li r5,17          -> li r5,<len>
: "${ADDR_CN_STRING:=0x684188}"        # pinned CN field, 24 bytes

CA=$1
if [ -z "$CA" ]; then
	CA="$D/dist/openpak-network-ca.pem"
	mkdir -p "$D/dist"
	profile=$(curl -fsS "$PROFILE_URL")
	url=$(printf '%s' "$profile" | python3 -I -c 'import json,sys; print(json.load(sys.stdin)["ca"]["url"])')
	pin=$(printf '%s' "$profile" | python3 -I -c 'import json,sys; print(json.load(sys.stdin)["ca"]["sha256"])')
	curl -fsS "$url" -o "$CA.new"
	[ "$(sha256sum "$CA.new" | cut -c1-64)" = "$pin" ] || { rm -f "$CA.new"; echo "CA does not match the profile pin" >&2; exit 1; }
	mv "$CA.new" "$CA"
fi

cn=$(openssl x509 -in "$CA" -noout -subject -nameopt multiline | sed -n 's/^ *commonName *= *//p')
[ -n "$cn" ] && [ ${#cn} -le 23 ] || { echo "CA CN must be 1-23 characters (fits the 24-byte vsh field): '$cn'" >&2; exit 1; }
len=${#cn}

mkdir -p "$CERT"
cp "$CA" "$CERT/CA01.cer"
cp "$CA" "$CERT/CA59.cer"

# CN NUL-padded to 24 bytes, as six big-endian 32-bit words.
words=$(printf '%s' "$cn" | python3 -I -c 'import sys; b=sys.stdin.buffer.read().ljust(24,b"\0"); print(" ".join("0x%08x"%int.from_bytes(b[i:i+4],"big") for i in range(0,24,4)))')
cmplen=$(printf '0x%08x' $((0x2f800000 + len)))
memlen=$(printf '0x%08x' $((0x38a00000 + len)))

skip_cn=0
[ "$cn" = "SCEI DNAS Root 05" ] && skip_cn=1   # route (b): CN == stock pin, CN pokes are no-ops

{
	echo "/* Generated by tools/stage.sh -- do not edit. CA CN: $cn ($len bytes) */"
	echo "#ifndef OPENPAK_CA_PATCH_H"
	echo "#define OPENPAK_CA_PATCH_H"
	echo "/* The CA whose CN drives this: $cn */"
	echo "#define OPENPAK_CA_CN \"$cn\""
	echo "#define OPENPAK_SKIP_CN_POKES $skip_cn   /* 1 when CN == \"SCEI DNAS Root 05\" (route b) */"
	echo ""
	echo "/* { vaddr, value_to_write, original_value_expected } -- the plugin writes value only if"
	echo "   the word already equals original (verify-before-patch; wrong firmware -> no-op). */"
	echo "static const struct { unsigned int addr, val, orig; } openpak_u32_pokes[] = {"
	echo "	{ ${ADDR_SHA1_BRANCH}u, 0x60000000u, 0x409e0008u }, /* file-content gate: bf 30,+8 -> nop */"
	if [ "$skip_cn" -eq 0 ]; then
		echo "	{ ${ADDR_CN_CMPLEN}u, ${cmplen}u, 0x2f800011u }, /* CN length compare: 17 -> $len */"
		echo "	{ ${ADDR_CN_MEMLEN}u, ${memlen}u, 0x38a00011u }, /* CN memcmp length: 17 -> $len */"
	fi
	echo "};"
	echo ""
	if [ "$skip_cn" -eq 0 ]; then
		echo "/* pinned CN string field at ${ADDR_CN_STRING} (24 bytes), overwritten with our CN. First"
		echo "   word must read 0x53434549 (\"SCEI\") before we touch it. */"
		echo "#define OPENPAK_CN_STRING_ADDR ${ADDR_CN_STRING}u"
		echo "#define OPENPAK_CN_STRING_ORIG0 0x53434549u"
		echo -n "static const unsigned int openpak_cn_words[6] = { "
		for w in $words; do printf '%su, ' "$w"; done
		echo "};"
	else
		echo "#define OPENPAK_CN_STRING_ADDR 0u   /* route (b): CN string unchanged */"
	fi
	echo ""
	echo "#endif"
} > "$HDR"

{
	echo "# OpenPak PS3 vsh pokes, firmware target 4.93 retail CEX unless ADDR_* overridden."
	echo "# CA CN = $cn ($len bytes).  Verify-before-patch originals in parentheses."
	echo "$ADDR_SHA1_BRANCH  = 0x60000000   # (orig 0x409e0008) file-content SHA-1 gate -> nop"
	if [ "$skip_cn" -eq 0 ]; then
		echo "$ADDR_CN_CMPLEN  = $cmplen   # (orig 0x2f800011) issuer-CN length compare -> $len"
		echo "$ADDR_CN_MEMLEN  = $memlen   # (orig 0x38a00011) issuer-CN memcmp length -> $len"
		echo "$ADDR_CN_STRING  : pinned CN string (24B) -> '$cn' padded:"
		echo "    $words"
	else
		echo "# CN == \"SCEI DNAS Root 05\": CN pokes and the string overwrite are omitted (route b)."
	fi
} > "$D/dist/poke-table.txt"

echo "staged dist/dev_flash/data/cert/{CA01,CA59}.cer and plugin/openpak_ca_patch.h for CN '$cn'"
[ "$skip_cn" -eq 1 ] && echo "note: CN matches the stock pin -> only the file-content poke is needed"
echo "poke table: dist/poke-table.txt"

# ---- name rewrite table ---------------------------------------------------------------------
# names/psn-names.txt is the bundled list; NAMES_EXTRA=<file> appends more entries of the same
# shape (this is where the network's single signed redirect list plugs in). Replacement must be
# exactly as long as the match: the plugin overwrites in place and never moves bytes.
NAMES="$D/names/psn-names.txt"
python3 -I - "$NAMES" "${NAMES_EXTRA:-}" "$D/plugin/openpak_names.h" "$D/dist/redirect-names.txt" <<'PY'
import sys
out = []
for path in sys.argv[1:3]:
    if not path:
        continue
    for ln, line in enumerate(open(path, encoding="ascii"), 1):
        line = line.rstrip("\n")
        if not line.strip() or line.lstrip().startswith("#"):
            continue
        cols = line.split("\t")
        if len(cols) != 2:
            sys.exit("%s:%d: want <match> TAB <replace>" % (path, ln))
        m, r = cols
        if len(m) != len(r):
            sys.exit("%s:%d: replacement must be the same length as the match (%d vs %d): %s" % (path, ln, len(m), len(r), m))
        if not (4 <= len(m) <= 40):
            sys.exit("%s:%d: match length must be 4..40" % (path, ln))
        if m == r:
            sys.exit("%s:%d: match equals replacement" % (path, ln))
        if (m, r) not in out:
            out.append((m, r))
if not out:
    sys.exit("no name entries")
def c(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'
with open(sys.argv[3], "w") as h:
    h.write("/* Generated by tools/stage.sh from names/psn-names.txt -- do not edit. */\n")
    h.write("#ifndef OPENPAK_NAMES_H\n#define OPENPAK_NAMES_H\n")
    h.write("#define OPENPAK_NAMES_N %d\n" % len(out))
    h.write("static const struct { const char *from, *to; unsigned char len; } openpak_names[OPENPAK_NAMES_N] = {\n")
    for m, r in out:
        h.write("\t{ %s, %s, %d },\n" % (c(m), c(r), len(m)))
    h.write("};\n#endif\n")
with open(sys.argv[4], "w") as t:
    for m, r in out:
        t.write("%s\t%s\n" % (m, r))
PY
echo "staged plugin/openpak_names.h ($(grep -c '^	{' "$D/plugin/openpak_names.h") name entries)"
